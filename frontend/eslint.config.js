// Flat config (ESLint 10). `package.json` has "type": "module", so this file is
// ESM and needs no .mjs extension.
//
// What this does not do: type-aware linting. typescript-eslint can read the
// program and check types, but `tsc -b --noEmit` already runs in `npm run
// typecheck` and in CI with `strict`, `noUnusedLocals`, `noUnusedParameters`
// and `noFallthroughCasesInSwitch` — turning it on here would re-typecheck 76
// files to report what tsc has already reported, at several times the runtime.
// ESLint is here for what tsc does not look at: hook rules, and the patterns
// that break Vite's fast refresh.

import js from "@eslint/js";
import globals from "globals";
import reactHooks from "eslint-plugin-react-hooks";
import reactRefresh from "eslint-plugin-react-refresh";
import tseslint from "typescript-eslint";

export default tseslint.config(
  {
    // dist/ is build output. mockServiceWorker.js is generated by msw's
    // postinstall and is not ours to lint or fix.
    ignores: ["dist/**", "public/mockServiceWorker.js"],
  },

  // The source: browser globals, TypeScript, React.
  {
    files: ["src/**/*.{ts,tsx}"],
    extends: [js.configs.recommended, tseslint.configs.recommended],
    languageOptions: {
      ecmaVersion: 2022,
      globals: globals.browser,
    },
    plugins: {
      "react-hooks": reactHooks,
      "react-refresh": reactRefresh,
    },
    rules: {
      ...reactHooks.configs["recommended-latest"].rules,
      // Vite's fast refresh only works on a module whose exports are all
      // components. `allowConstantExport` permits the `const` beside them,
      // which is how the shadcn-style variants in components/ui are written.
      "react-refresh/only-export-components": [
        "warn",
        { allowConstantExport: true },
      ],
      // Downgraded from error, deliberately. This rule is new in
      // eslint-plugin-react-hooks v7 and it fires six times on code that
      // predates it — in useMediaQuery, PageToolbar, CommandPalette, TopBar and
      // ChatPage. Some of those are intentional: useMediaQuery re-reads
      // `matchMedia` in the effect to cover the query changing between render
      // and effect, which is the thing the rule tells you not to do and also
      // the reason that line exists.
      //
      // Fixing them means reworking how those five components synchronise
      // state, which is a behaviour change in a codebase with no frontend unit
      // tests — not something to bundle into "add a linter". The `lint` script
      // pins the warning count instead, so these can be worked off one at a
      // time and no new ones can appear.
      "react-hooks/set-state-in-effect": "warn",

      // An unused name prefixed with _ is deliberate — a positional argument
      // that has to be there, or a destructured key being dropped.
      "@typescript-eslint/no-unused-vars": [
        "error",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
        },
      ],
    },
  },

  // This file and anything else that runs in Node rather than the browser.
  {
    files: ["*.{js,ts}", "vite.config.ts"],
    extends: [js.configs.recommended, tseslint.configs.recommended],
    languageOptions: { globals: globals.node },
  },
);
